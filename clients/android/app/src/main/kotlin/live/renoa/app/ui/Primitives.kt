/** Parses SVG path data once per distinct string. */
@Composable
fun rememberSvgPath(data: String): Path = remember(data) { PathParser().parsePathString(data).toPath() }

/** A Phosphor icon: filled path data on Phosphor's 256 by 256 grid, tinted like text. */
@Composable
fun PathIcon(data: String, tint: Color, modifier: Modifier = Modifier, size: Dp = 20.dp) {
    val path = rememberSvgPath(data)
    Canvas(modifier.size(size)) {
        val s = this.size.minDimension / 256f
        withTransform({ scale(s, s, Offset.Zero) }) { drawPath(path, tint) }
    }
}

